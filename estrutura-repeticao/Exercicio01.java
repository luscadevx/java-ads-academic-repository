package aulasjava;

public class Exercicio01 {
    public static void main(String[] args) {
        
        int numero = 1;
        
        System.out.println("--- Contagem de 1 a 10 (While) ---");
        
        while (numero <= 10) {
            System.out.println("Número: " + numero);
            numero += 1;
        }
    }
}